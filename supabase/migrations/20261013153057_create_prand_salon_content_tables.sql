/*
# Create PRAND SALON content tables

1. Purpose
- Create the durable content foundation for the PRAND SALON prototype.
- Keep the current frontend prototype independent from the database until a reviewed content-loading flow is added.

2. New Tables
- `salon_branches`: verified branch names and address details, without phone numbers, hours, or map coordinates.
- `salon_services`: editable service names, descriptions, icons, and verified price notes.
- `barber_profiles`: editable barber profile content, with an explicit demo flag and no invented records inserted.
- `gallery_items`: editable hairstyle and salon gallery records with centralized image URLs and alt text.
- `customer_reviews`: review submissions and moderation status for a future verified review flow; no fake reviews are inserted.

3. Common Columns
- `id`: UUID primary key generated by the database.
- `sort_order`: stable editorial ordering.
- `is_published`: controls whether trusted content is ready for public display.
- `created_at` and `updated_at`: audit timestamps maintained by the application or trusted admin process.

4. Security
- Row Level Security is enabled on every new table.
- Public visitors can read only rows marked `is_published` where applicable.
- Browser roles cannot insert, update, or delete content. Trusted administration can use the service role or a future protected admin flow.
- Review rows are never publicly readable unless they are explicitly marked `approved` and `is_published`.
- No authentication, user ownership, phone numbers, prices, staff names, ratings, or seed content are added by this migration.

5. Important Notes
- This migration does not replace the existing local placeholder data in the frontend.
- This migration does not create an admin dashboard or public review submission endpoint.
- The existing asset filenames remain frontend-managed until a reviewed storage/content workflow is added.
*/

CREATE TABLE IF NOT EXISTS public.salon_branches (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  address text NOT NULL,
  landmark text,
  area text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.salon_services (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  description text NOT NULL,
  icon text NOT NULL,
  price_note text,
  sort_order integer NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.barber_profiles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  display_name text NOT NULL,
  specialty text,
  bio text,
  portrait_url text,
  gallery_urls text[] NOT NULL DEFAULT '{}',
  is_demo boolean NOT NULL DEFAULT false,
  sort_order integer NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.gallery_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  category text NOT NULL,
  image_url text NOT NULL,
  label text NOT NULL,
  alt_text text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  is_published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.customer_reviews (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  display_name text,
  review_text text NOT NULL,
  rating smallint,
  status text NOT NULL DEFAULT 'pending',
  is_published boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT customer_reviews_rating_range CHECK (rating IS NULL OR rating BETWEEN 1 AND 5),
  CONSTRAINT customer_reviews_status_values CHECK (status IN ('pending', 'approved', 'rejected'))
);

CREATE INDEX IF NOT EXISTS salon_branches_published_order_idx
  ON public.salon_branches (is_published, sort_order);
CREATE INDEX IF NOT EXISTS salon_services_published_order_idx
  ON public.salon_services (is_published, sort_order);
CREATE INDEX IF NOT EXISTS barber_profiles_published_order_idx
  ON public.barber_profiles (is_published, sort_order);
CREATE INDEX IF NOT EXISTS gallery_items_published_category_order_idx
  ON public.gallery_items (is_published, category, sort_order);
CREATE INDEX IF NOT EXISTS customer_reviews_public_status_idx
  ON public.customer_reviews (is_published, status, created_at DESC);

ALTER TABLE public.salon_branches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.salon_services ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.barber_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gallery_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customer_reviews ENABLE ROW LEVEL SECURITY;

